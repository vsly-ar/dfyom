// Writes src/core/design/engraving/preset-svgs.ts: the preset SVG files of
// src/core/design/engraving/presets/ as string constants (engraved-patterns.md § Presets). Core is
// also loaded by tools without a bundler (Playwright's TypeScript loader in e2e), so the texts are
// a plain module rather than `?raw` imports. A test checks the module equals the files.
// Usage: node scripts/engraving-presets.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const dir = join(root, 'src/core/design/engraving/presets')
const out = join(root, 'src/core/design/engraving/preset-svgs.ts')

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
const lines = [
  '// Generated by scripts/engraving-presets.mjs from presets/*.svg; do not edit (a test checks it).',
  '// Doc: docs/modes/engraved-patterns.md#implementation-e3',
  '',
  '/** Preset id → the SVG file text. */',
  'export const PRESET_SVGS: Readonly<Record<string, string>> = {',
  ...files.map(
    (f) =>
      `  ${JSON.stringify(f.replace(/\.svg$/, ''))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`,
  ),
  '}',
  '',
]
writeFileSync(out, lines.join('\n'))
console.log(`${files.length} presets written to ${out}`)
