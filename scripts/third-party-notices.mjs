// Collects the licence notices of every third-party package in the packaged app into
// out/THIRD_PARTY_NOTICES.txt (shipped in DFYOM.app/Contents/Resources, shown by Help →
// Open-source licences). Run after `electron-vite build` (`npm run package` does): the bundled
// packages are read from the module comments Rolldown writes into out/**/*.js, the main-process
// runtime packages from electron-builder.config.mjs (MAIN_EXTERNALS), the vendored assets from
// VENDORED below. Fails on a package without licence text or with a licence outside ALLOWED.
// Doc: docs/conventions/packaging.md#third-party-notices
