/**
 * True when the SPDX expression can be met with ALLOWED licences: an `OR` needs one allowed side,
 * an `AND` both; `WITH <exception>` only adds permissions, so it is ignored. Malformed → false.
 */
export function licenceAllowed(expression) {
  if (typeof expression !== 'string') return false
  const tokens = expression.match(/\(|\)|[^\s()]+/g) ?? []
  let i = 0
  const primary = () => {
    const token = tokens[i++]
    if (token === '(') {
      const value = or()
      if (tokens[i++] !== ')') throw new Error('unbalanced')
      return value
    }
    if (token === undefined || token === ')' || /^(AND|OR|WITH)$/.test(token))
      throw new Error('unexpected token')
    if (tokens[i] === 'WITH') i += 2
    // `GPL-2.0+` is the deprecated spelling of GPL-2.0-or-later
    const base = token.replace(/\+$/, '')
    return ALLOWED.has(base) || (base !== token && ALLOWED.has(`${base}-or-later`))
  }
  const and = () => {
    let value = primary()
    while (tokens[i] === 'AND') {
      i++
      value = primary() && value
    }
    return value
  }
  const or = () => {
    let value = and()
    while (tokens[i] === 'OR') {
      i++
      value = and() || value
    }
    return value
  }
  try {
    const value = or()
    return i === tokens.length && value
  } catch {
    return false
  }
}

/** The SPDX expression of a package.json, the legacy `{type}` / `licenses` forms included. */
export function packageLicence(pkg) {
  const field = pkg.license ?? pkg.licenses
  if (typeof field === 'string') return field
  if (Array.isArray(field)) {
    const types = field.map((l) => (typeof l === 'string' ? l : l?.type)).filter(Boolean)
    return types.length > 1 ? `(${types.join(' OR ')})` : types[0]
  }
  return field?.type
}

/** The licence and notice files at the top of a package directory (LICENSE, COPYING, NOTICE …). */
export function licenceFiles(dir) {
  return readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)([.\-_].*)?$/i.test(f))
    .filter((f) => statSync(join(dir, f)).isFile())
    .sort()
}

/** The package directory holding `file` (the segment after its last node_modules/). */
function packageDirOf(file) {
  const parts = file.split(sep)
  const at = parts.lastIndexOf('node_modules')
  if (at < 0 || at + 1 >= parts.length) return undefined
  const length = parts[at + 1].startsWith('@') ? at + 3 : at + 2
  return parts.slice(0, length).join(sep)
}

function jsFiles(dir) {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile() && /\.(c|m)?js$/.test(e.name))
    .map((e) => join(e.parentPath, e.name))
}

/**
 * Package directories whose modules Rolldown bundled into out/**\/*.js, read from the
 * `// <module path>` comment it writes above each module. Throws when a file has none (a minified
 * build drops them, which would silently drop the renderer's packages from the notices).
 */
export function bundledPackageDirs(outDir = OUT_DIR) {
  if (!existsSync(outDir)) throw new Error(`${outDir} is missing: run electron-vite build first`)
  const dirs = new Set()
  for (const file of jsFiles(outDir)) {
    const comments = readFileSync(file, 'utf8').match(/^\/\/ [^\s]+\.(?:[cm]?[jt]sx?)$/gm) ?? []
    if (comments.length === 0)
      throw new Error(`${relative(ROOT, file)} has no module comments (minified build?)`)
    for (const comment of comments) {
      const dir = packageDirOf(resolve(ROOT, comment.slice(3)))
      if (dir !== undefined) dirs.add(dir)
    }
  }
  return dirs
}

function readPackage(dir) {
  return JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
}

function repositoryUrl(pkg) {
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  return (repo ?? pkg.homepage ?? '').replace(/^git\+/, '')
}

/**
 * Every shipped third-party component with its licence and texts; `problems` lists what fails the
 * script. Bundled and runtime copies of one name@version are one entry.
 */
export async function collectNotices({ outDir = OUT_DIR } = {}) {
  const { runtimeClosureDirs } = await import(
    pathToFileURL(join(ROOT, 'electron-builder.config.mjs')).href
  )
  const sources = [
    ...[...bundledPackageDirs(outDir)].map((dir) => [dir, 'renderer/main bundle']),
    ...[...runtimeClosureDirs()].map((dir) => [dir, 'main process runtime']),
  ]
  const byId = new Map()
  const problems = []
  for (const [dir, usedIn] of sources) {
    const pkg = readPackage(dir)
    const id = `${pkg.name}@${pkg.version}`
    const known = byId.get(id)
    if (known !== undefined) {
      if (!known.usedIn.includes(usedIn)) known.usedIn.push(usedIn)
      continue
    }
    const licence = packageLicence(pkg)
    const texts = licenceTexts(dir, pkg.name, licence)
    if (texts.length === 0) problems.push(`${id}: no licence file in ${relative(ROOT, dir)}`)
    if (!licenceAllowed(licence)) problems.push(`${id}: licence ${JSON.stringify(licence)}`)
    byId.set(id, {
      name: pkg.name,
      version: pkg.version,
      licence: licence ?? 'UNKNOWN',
      usedIn: [usedIn],
      source: repositoryUrl(pkg),
      texts,
    })
  }
  for (const v of VENDORED) {
    const path = join(ROOT, v.notices)
    const text = existsSync(path) ? readFileSync(path, 'utf8').trim() : ''
    if (text === '') problems.push(`${v.name}: no notices at ${v.notices}`)
    if (!licenceAllowed(v.licence)) problems.push(`${v.name}: licence ${v.licence}`)
    byId.set(v.name, {
      name: v.name,
      version: 'vendored',
      licence: v.licence,
      usedIn: [v.usedIn],
      source: v.source,
      texts: [text],
    })
  }
  for (const e of EMBEDDED) {
    if (!licenceAllowed(e.licence)) problems.push(`${e.name}: licence ${e.licence}`)
    byId.set(e.name, {
      name: e.name,
      version: 'embedded',
      licence: e.licence,
      usedIn: ['main process runtime'],
      source: e.source,
      texts: [e.text.replace('{MIT}', MIT_TEXT)],
    })
  }
  const entries = [...byId.values()].sort((a, b) => a.name.localeCompare(b.name))
  return { entries, problems }
}

/** Licence expression → package names, most used first. */
export function summaryByLicence(entries) {
  const groups = new Map()
  for (const e of entries) groups.set(e.licence, [...(groups.get(e.licence) ?? []), e.name])
  return [...groups].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
}

export function renderNotices(entries) {
  const rule = '-'.repeat(78)
  const lines = [
    'DFYOM third-party notices',
    '=========================',
    '',
    'DFYOM is free software under the GNU General Public License, version 3 or later',
    '(LICENSE.txt). It ships the third-party software below, each under its own licence, all',
    'compatible with GPL-3.0-or-later. Electron and Chromium ship their notices next to this',
    'file: LICENSE.electron.txt and LICENSES.chromium.html.',
    '',
    'Generated by scripts/third-party-notices.mjs.',
    '',
    'Summary by licence:',
    ...summaryByLicence(entries).map(([licence, names]) => `  ${licence} (${names.length})`),
    '',
    'Components:',
    ...entries.map((e) => `  ${e.name} ${e.version} - ${e.licence}`),
  ]
  for (const e of entries) {
    lines.push('', rule, `${e.name} ${e.version}`, `Licence: ${e.licence}`)
    lines.push(`Used in: ${e.usedIn.join(', ')}`)
    if (e.source) lines.push(`Source: ${e.source}`)
    for (const text of e.texts) lines.push('', text)
  }
  return lines.join('\n') + '\n'
}

async function main() {
  const { entries, problems } = await collectNotices()
  console.log(`Third-party notices: ${entries.length} components`)
  for (const [licence, names] of summaryByLicence(entries))
    console.log(`  ${licence} (${names.length}): ${names.join(', ')}`)
  if (problems.length > 0) {
    console.error('\nThird-party notices failed:')
    for (const p of problems) console.error(`  ${p}`)
    process.exit(1)
  }
  writeFileSync(NOTICES_PATH, renderNotices(entries))
  console.log(`Wrote ${relative(ROOT, NOTICES_PATH)}`)
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === import.meta.filename) await main()
