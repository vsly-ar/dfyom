const curvesOf = (paths: readonly Subpath[]): Curve[] => paths.flatMap((p) => [...p.curves])

function timeIt(f: () => void): number {
  for (let i = 0; i < 3; i++) f() // warm-up
  const runs: number[] = []
  const until = performance.now() + 300
  while (runs.length < 5 || (performance.now() < until && runs.length < 2000)) {
    const t0 = performance.now()
    f()
    runs.push(performance.now() - t0)
  }
  runs.sort((a, b) => a - b)
  return runs[Math.floor(runs.length / 2)]!
}

interface Row {
  arcs: number
  lines: number
  dev: number
  kink: number
  minLen: number
  minR: number
  maxR: number
  forced: number
  micro: number
  ms: number
}

function measure(curves: readonly Curve[], a: Approach, oracle = true, tol = 0.01): Row {
  const fits: FitResult[] = curves.map((c) => fitCurve(c, a, { tol }))
  const elems = fits.flatMap((f) => elemsOf(f))
  let dev = 0
  let kink = 0
  if (oracle)
    curves.forEach((c, i) => {
      dev = Math.max(dev, deviation(c, fits[i]!))
      kink = Math.max(kink, continuity(c, fits[i]!).kink)
    })
  const arcs = elems.filter((e) => e.bulge !== 0)
  const radii = arcs.map(elemRadius)
  return {
    arcs: arcs.length,
    lines: elems.length - arcs.length,
    dev,
    kink,
    minLen: elems.map(elemLength).reduce((m, x) => Math.min(m, x), Infinity),
    minR: radii.length ? radii.reduce((m, x) => Math.min(m, x), Infinity) : NaN,
    maxR: radii.length ? radii.reduce((m, x) => Math.max(m, x), 0) : NaN,
    forced: fits.reduce((s, f) => s + f.forced, 0),
    micro: fits.reduce((s, f) => s + f.chains.filter((ch) => ch.micro).length, 0),
    ms: timeIt(() => curves.forEach((c) => fitCurve(c, a, { tol }))),
  }
}

const num = (x: number, d = 3): string =>
  !Number.isFinite(x)
    ? '–'
    : x === 0
      ? '0'
      : x >= 1e4 || x < 1e-3
        ? x.toExponential(1)
        : x.toFixed(d)

/** S1's 3-point arc subdivision: element count and joins with a kink > 1 mrad. */
function s1Baseline(c: Case, d: string): string {
  const loops = parsePath(d, 0.01)
  let elems = 0
  let kinks = 0
  for (const l of loops) {
    const n = l.verts.length
    elems += n
    for (let i = 0; i < n; i++) {
      const v = l.verts
      const e = (k: number): Elem => {
        const p = v[k % n]!
        const q = v[(k + 1) % n]!
        return { a: { x: p[0], y: p[1] }, b: { x: q[0], y: q[1] }, bulge: p[2] }
      }
      const t1 = elemTangents(e(i)).t1
      const t0 = elemTangents(e(i + 1)).t0
      if (Math.abs(Math.atan2(cross(t1, t0), dot(t1, t0))) > 1e-3) kinks++
    }
  }
  return `| ${c.name} | ${elems} | ${kinks} |`
}

